"""Generate a source inventory without executing the application or connecting to services."""
from __future__ import annotations

import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def inventory() -> str:
    rows = []
    files = [ROOT / 'backend/app/main.py', *sorted((ROOT / 'backend/app/api').rglob('*.py'))]
    for path in files:
        tree = ast.parse(path.read_text(encoding='utf-8'))
        prefix = ''
        for node in ast.walk(tree):
            if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id == 'APIRouter':
                prefix = next((ast.literal_eval(k.value) for k in node.keywords if k.arg == 'prefix'), '')
        for function in tree.body:
            if not isinstance(function, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            for decorator in function.decorator_list:
                if not isinstance(decorator, ast.Call) or not isinstance(decorator.func, ast.Attribute):
                    continue
                method = decorator.func.attr.upper()
                if method not in {'GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'HEAD', 'OPTIONS'} or not decorator.args:
                    continue
                route = prefix + ast.literal_eval(decorator.args[0])
                if '/api/v1/' in path.as_posix():
                    route = '/api/v1' + route
                dependencies = [ast.unparse(n.args[0]) for n in ast.walk(function.args)
                                if isinstance(n, ast.Call) and isinstance(n.func, ast.Name)
                                and n.func.id == 'Depends' and n.args]
                identity = ', '.join(d for d in dependencies if d != 'get_session') or 'public / handler checks'
                payload = ', '.join(ast.unparse(a.annotation) for a in function.args.args
                                    if a.annotation and a.arg == 'payload') or 'path/query/header/file'
                response = next((ast.unparse(k.value) for k in decorator.keywords if k.arg == 'response_model'), 'inferred / explicit Response')
                mutates = method in {'POST', 'PUT', 'PATCH', 'DELETE'} or (route.startswith('/api/v1/payments/') and route.endswith('/status'))
                calls = sorted({ast.unparse(n.func) for n in ast.walk(function) if isinstance(n, ast.Call)
                                and isinstance(n.func, ast.Name) and n.func.id not in {'Depends', 'HTTPException', 'str', 'int', 'bool', 'len', 'select'}})
                source = f'{path.relative_to(ROOT).as_posix()}:{function.lineno}'
                rows.append((route, method, identity, payload, response, 'mutation/reconciliation' if mutates else 'read; inspect delegates', source, ', '.join(calls)))
    lines = ['# API source inventory', '',
             f'{len(rows)} declared HTTP operations. Generated by `python scripts/security-inventory.py`.', '',
             'This is a syntactic inventory, not proof of authorization. Dependencies may enforce policy transitively; public handlers can apply object visibility checks. Rate-limit rules live in `backend/app/main.py` and Nginx. GET payment status handlers can reconcile and commit; treat them as sensitive operations. Service-level SQL, ownership and integration checks are discussed in APPLICATION-SECURITY.md and PAYMENT-SECURITY-AUDIT.md.', '',
             '| Route | Method | Identity / role dependency | Request model | Response model | Effects | Source | Direct delegates |',
             '|---|---|---|---|---|---|---|---|']
    lines.extend('| ' + ' | '.join(str(c).replace('|', '\\|') for c in row) + ' |' for row in sorted(rows))
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    destination = ROOT / 'docs/security/API-INVENTORY.md'
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(inventory(), encoding='utf-8')
    print(destination)
