def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    if sha256_file(SOURCE) != EXPECTED_SOURCE_SHA256:
        raise SystemExit("external_import.py no longer matches the reviewed source")
    payload = "".join(PATCH_ZLIB_BASE64.split())
    patch = zlib.decompress(base64.b64decode(payload))
    if hashlib.sha256(patch).hexdigest() != EXPECTED_PATCH_SHA256:
        raise SystemExit("decoded importer patch checksum mismatch")
    patch_path = Path(".external-import-hardening.patch")
    patch_path.write_bytes(patch)
    subprocess.run(["git", "apply", "--check", str(patch_path)], check=True)
    subprocess.run(["git", "apply", str(patch_path)], check=True)
    patch_path.unlink()
    if sha256_file(SOURCE) != EXPECTED_RESULT_SHA256:
        raise SystemExit("patched external_import.py checksum mismatch")


if __name__ == "__main__":
    main()
